// setupCookie carries the one-time token after the first visit, so the
// token leaves the address bar, and with it the browser history and any
// screen being shared, on the first request.
const setupCookie = "sextant_setup"

// SetupOptions is what main knows when it starts without a way to sign
// anyone in (design 0013).
type SetupOptions struct {
	DataDir string
	// Token is the one-time secret printed to the log. Whoever can read the
	// log can run setup; nobody else can.
	Token string
	// Deployment names the settings fixed by flag or environment; setup
	// never writes those to the data directory.
	Deployment    map[string]bool
	SecureCookies bool
	Locale        string
	// Keys and Settings are the values in force now: from the deployment,
	// or from an earlier setup that did not finish.
	Keys     config.Keys
	Settings config.Settings
	// SeedRepo creates the starter fleet repository in dir, leaving an
	// existing repository as it is.
	SeedRepo func(ctx context.Context, dir string) error
	// TestRepo checks that an existing repository answers with the given
	// credential; CloneRepo clones it into dir. The credential is used for
	// that one command.
	TestRepo  func(ctx context.Context, url, user, token string) error
	CloneRepo func(ctx context.Context, url, user, token, dir string) error
	// NewSignin discovers an identity provider and returns a login flow
	// against it, for the test sign-in.
	NewSignin func(ctx context.Context, c SigninConfig) (SigninFlow, error)
	// Check loads the configuration the way the next start will, with what
	// setup wrote. An error is what that start would refuse with.
	Check func() error
	// Restart starts the console again with what setup wrote, once the
	// current request has been answered.
	Restart func()
	Log     *slog.Logger
}

// SigninConfig is what the sign-in step asks, plus what a test login
// needs to run with it.
type SigninConfig struct {
	Issuer, ClientID, ClientSecret, RedirectURL, GroupsClaim string
	SessionKey                                               []byte
	Secure                                                   bool
}

// SigninFlow is a login against one identity provider: Login sends the
// browser there, Identify reads who came back, without a session.
type SigninFlow interface {
	Login(w http.ResponseWriter, r *http.Request)
	Identify(w http.ResponseWriter, r *http.Request) (identity.User, error)
}

// signinTry is the provider being tried. The secret stays in memory until
// setup finishes, so an abandoned attempt leaves nothing on disk.
type signinTry struct {
	view   signinView
	secret string
	flow   SigninFlow
}

// Setup serves the first-start pages.
type Setup struct {
	opt  SetupOptions
	tmpl *template.Template

	mu sync.Mutex
	// pending holds keys generated by this process and not yet written.
	// They are written when the operator confirms the recovery file is
	// stored, so a key nobody saved never reaches the disk, and a restart
	// before that point simply generates new ones: nothing used them yet.
	pending config.Keys
	// signin is the provider being tried in the sign-in step.
	signin *signinTry
}

// NewSetupToken returns a fresh one-time setup token.
func NewSetupToken() (string, error) {
	b := make([]byte, 24)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(b), nil
}

// NewSetup builds the setup pages. It generates every secret that neither
// the deployment nor an earlier setup provided.
func NewSetup(opt SetupOptions) (*Setup, error) {
	if opt.Token == "" {
		return nil, errors.New("setup needs a token")
	}
	if opt.DataDir == "" {
		return nil, errors.New("setup needs a data directory (--data-dir) to keep its answers in")
	}
	// Absolute, because the repository path is written to settings.json and
	// read back by a process that may not start in the same directory.
	abs, err := filepath.Abs(opt.DataDir)
	if err != nil {
		return nil, err
	}
	opt.DataDir = abs
	if opt.Log == nil {
		opt.Log = slog.New(slog.DiscardHandler)
	}
	t, err := template.ParseFS(assets, "templates/setup.html")
	if err != nil {
		return nil, err
	}
	s := &Setup{opt: opt, tmpl: t}
	for _, k := range []struct{ have, gen *string }{
		{&opt.Keys.SessionKey, &s.pending.SessionKey},
		{&opt.Keys.SecretKey, &s.pending.SecretKey},
		{&opt.Keys.CheckinToken, &s.pending.CheckinToken},
	} {
		if *k.have != "" {
			continue
		}
		if *k.gen, err = randomKey(); err != nil {
			return nil, err
		}
	}
	return s, nil
}

// randomKey is base64 of 32 random bytes: the format all three secrets
// already take, so a value can move between keys.json and the environment.
func randomKey() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.StdEncoding.EncodeToString(b), nil
}

// Routes mounts setup. Everything a signed-in console would answer on the
// root and the login page says instead that setup is under way.
func (s *Setup) Routes(mux *http.ServeMux) {
	mux.Handle("GET /static/", staticHandler())
	mux.HandleFunc("GET /{$}", s.handleWaiting)
	mux.HandleFunc("GET /login", s.handleWaiting)
	mux.HandleFunc("GET /setup", s.handleSetup)
	mux.HandleFunc("GET /setup/recovery-key", s.guard(s.handleRecoveryKey))
	mux.HandleFunc("POST /setup/keys", s.guard(s.handleKeys))
	mux.HandleFunc("POST /setup/repo", s.guard(s.handleRepo))
	mux.HandleFunc("POST /setup/signin", s.guard(s.handleSignin))
	mux.HandleFunc("GET /setup/signin/start", s.guard(s.handleSigninStart))
	// Not guarded: the provider sends the browser back from another site,
	// and a SameSite=Strict cookie does not come along on that request.
	// The sealed flow cookie and the state stand in for it, and only the
	// guarded start above hands those out.
	mux.HandleFunc("GET /callback", s.handleCallback)
}

// authorized reports whether the request carries the setup token in its
// cookie. Constant-time, so the comparison does not leak the token a byte
// at a time to someone timing failed attempts.
func (s *Setup) authorized(r *http.Request) bool {
	c, err := r.Cookie(setupCookie)
	return err == nil && subtle.ConstantTimeCompare([]byte(c.Value), []byte(s.opt.Token)) == 1
}

// guard admits only the holder of the token. A POST must also come from a
// page of this console: the cookie is SameSite=Strict already, and the
// Origin check covers a browser that does not honour that.
func (s *Setup) guard(h http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if !s.authorized(r) {
			s.render(w, http.StatusForbidden, setupPage{Step: "waiting"})
			return
		}
		if r.Method == http.MethodPost {
			if o := r.Header.Get("Origin"); o != "" {
				if u, err := url.Parse(o); err != nil || u.Host != r.Host {
					http.Error(w, "cross-origin request refused", http.StatusForbidden)
					return
				}
			}
		}
		h(w, r)
	}
}

func (s *Setup) handleWaiting(w http.ResponseWriter, _ *http.Request) {
	s.render(w, http.StatusServiceUnavailable, setupPage{Step: "waiting"})
}

// handleSetup trades the token in the link for a cookie and shows the
// current step.
func (s *Setup) handleSetup(w http.ResponseWriter, r *http.Request) {
	if tok := r.URL.Query().Get("token"); tok != "" {
		if subtle.ConstantTimeCompare([]byte(tok), []byte(s.opt.Token)) != 1 {
			s.render(w, http.StatusForbidden, setupPage{Step: "waiting"})
			return
		}
		http.SetCookie(w, &http.Cookie{Name: setupCookie, Value: s.opt.Token, Path: "/",
			HttpOnly: true, Secure: s.opt.SecureCookies, SameSite: http.SameSiteStrictMode})
		http.Redirect(w, r, "/setup", http.StatusSeeOther)
		return
	}
	s.guard(func(w http.ResponseWriter, r *http.Request) {
		s.mu.Lock()
		defer s.mu.Unlock()
		s.render(w, http.StatusOK, s.signinPage(r, "", ""))
	})(w, r)
}

// handleRecoveryKey offers the secret key as a file. Only a key setup
// made itself: one the deployment set is already wherever the deployment
// keeps its secrets, and this page has no business copying it around.
func (s *Setup) handleRecoveryKey(w http.ResponseWriter, r *http.Request) {
	key := s.recoveryKey()
	if key == "" {
		http.NotFound(w, r)
		return
	}
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	w.Header().Set("Content-Disposition", `attachment; filename="sextant-recovery-key.txt"`)
	w.Header().Set("Cache-Control", "no-store")
	_, _ = fmt.Fprintf(w, `Sextant recovery key, created %s

SEXTANT_SECRET_KEY=%s

Every disk recovery key and every secret typed into the console is sealed
with this key in the database. A restored database cannot be read without
it. Keep this file somewhere the console's own failure cannot reach: a
password manager or a sealed envelope, not the server itself.
`, time.Now().UTC().Format("2006-01-02"), key)
}

func (s *Setup) recoveryKey() string {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.pending.SecretKey != "" {
		return s.pending.SecretKey
	}
	if s.opt.Deployment["SECRET_KEY"] {
		return ""
	}
	return s.opt.Keys.SecretKey
}

// handleKeys writes the generated keys once the operator has the recovery
// file. Keys already in keys.json stay as they are, and keys the
// deployment set are never written: a secret copied from the environment
// to a file is a second place to leak it from.
func (s *Setup) handleKeys(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.pending.SecretKey != "" && r.PostFormValue("stored") != "yes" {
		s.renderLocked(w, http.StatusUnprocessableEntity, "setup.keys.not_stored")
		return
	}
	_, onDisk, err := config.ReadDataDir(s.opt.DataDir)
	if err != nil {
		s.opt.Log.Error("setup: reading the data directory", "err", err)
		s.renderLocked(w, http.StatusInternalServerError, "setup.write_failed")
		return
	}
	for _, k := range []struct{ dst, gen *string }{
		{&onDisk.SessionKey, &s.pending.SessionKey},
		{&onDisk.SecretKey, &s.pending.SecretKey},
		{&onDisk.CheckinToken, &s.pending.CheckinToken},
	} {
		if *k.gen != "" && *k.dst == "" {
			*k.dst = *k.gen
		}
	}
	if err := config.WriteKeys(s.opt.DataDir, onDisk); err != nil {
		s.opt.Log.Error("setup: writing keys", "err", err)
		s.renderLocked(w, http.StatusInternalServerError, "setup.write_failed")
		return
	}
	for _, k := range []struct{ gen, have *string }{
		{&s.pending.SessionKey, &s.opt.Keys.SessionKey},
		{&s.pending.SecretKey, &s.opt.Keys.SecretKey},
		{&s.pending.CheckinToken, &s.opt.Keys.CheckinToken},
	} {
		if *k.gen != "" {
			*k.have, *k.gen = *k.gen, ""
		}
	}
	s.opt.Log.Info("setup: keys written", "dir", s.opt.DataDir)
	http.Redirect(w, r, "/setup", http.StatusSeeOther)
}

// handleRepo starts the fleet repository in the data directory.
func (s *Setup) handleRepo(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.step() != "repo" {
		http.Redirect(w, r, "/setup", http.StatusSeeOther)
		return
	}
	if r.PostFormValue("choice") == "existing" {
		s.useExistingRepo(w, r)
		return
	}
	if s.opt.SeedRepo == nil {
		http.Redirect(w, r, "/setup", http.StatusSeeOther)
		return
	}
	dir := filepath.Join(s.opt.DataDir, "overlay")
	if err := s.opt.SeedRepo(r.Context(), dir); err != nil {
		s.opt.Log.Error("setup: starting the fleet repository", "dir", dir, "err", err)
		s.renderLocked(w, http.StatusInternalServerError, "setup.repo.failed")
		return
	}
	if err := s.saveSettings(func(st *config.Settings) { st.RepoDir = dir }); err != nil {
		s.opt.Log.Error("setup: writing settings", "err", err)
		s.renderLocked(w, http.StatusInternalServerError, "setup.write_failed")
		return
	}
	s.opt.Settings.RepoDir = dir
	s.opt.Log.Info("setup: fleet repository started", "dir", dir)
	http.Redirect(w, r, "/setup", http.StatusSeeOther)
}

// useExistingRepo tests or clones a repository the organisation already
// has. Test answers on the same page; use clones it and records where the
// credential should go, which the next start hands to the console's own
// forge identity (ADR 0022). The token is never put back into the page.
func (s *Setup) useExistingRepo(w http.ResponseWriter, r *http.Request) {
	in := repoForm{URL: strings.TrimSpace(r.PostFormValue("url")), User: strings.TrimSpace(r.PostFormValue("user"))}
	token := strings.TrimSpace(r.PostFormValue("token"))
	page := func(status int, errKey, detail string) {
		p := s.page(errKey)
		p.Detail, p.Repo = detail, in
		s.render(w, status, p)
	}
	if s.opt.TestRepo == nil || s.opt.CloneRepo == nil {
		page(http.StatusNotImplemented, "setup.repo.existing_unavailable", "")
		return
	}
	if (token == "") != (in.User == "") {
		page(http.StatusUnprocessableEntity, "setup.repo.account_and_token", "")
		return
	}
	if r.PostFormValue("action") != "use" {
		if err := s.opt.TestRepo(r.Context(), in.URL, in.User, token); err != nil {
			page(http.StatusUnprocessableEntity, "setup.repo.test_failed", err.Error())
			return
		}
		in.Tested = true
		page(http.StatusOK, "", "")
		return
	}
	dir := filepath.Join(s.opt.DataDir, "overlay")
	if err := s.opt.CloneRepo(r.Context(), in.URL, in.User, token, dir); err != nil {
		page(http.StatusUnprocessableEntity, "setup.repo.test_failed", err.Error())
		return
	}
	host := ""
	if u, err := url.Parse(in.URL); err == nil && u.Scheme != "file" {
		host = u.Hostname()
	}
	if token != "" && host != "" {
		_, keys, err := config.ReadDataDir(s.opt.DataDir)
		if err == nil {
			keys.ForgeToken = token
			err = config.WriteKeys(s.opt.DataDir, keys)
		}
		if err != nil {
			s.opt.Log.Error("setup: writing the forge token", "err", err)
			page(http.StatusInternalServerError, "setup.write_failed", "")
			return
		}
	}
	if err := s.saveSettings(func(st *config.Settings) {
		st.RepoDir, st.GitRemote = dir, "origin"
		if token != "" && host != "" {
			st.ForgeHost, st.ForgeUser = host, in.User
		}
	}); err != nil {
		s.opt.Log.Error("setup: writing settings", "err", err)
		page(http.StatusInternalServerError, "setup.write_failed", "")
		return
	}
	s.opt.Settings.RepoDir, s.opt.Settings.GitRemote = dir, "origin"
	s.opt.Log.Info("setup: fleet repository cloned", "dir", dir, "host", host)
	http.Redirect(w, r, "/setup", http.StatusSeeOther)
}

// handleSignin checks a provider, or finishes setup with the one that
// was tested.
func (s *Setup) handleSignin(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.step() != "signin" {
		http.Redirect(w, r, "/setup", http.StatusSeeOther)
		return
	}
	if r.PostFormValue("action") == "finish" {
		s.finish(w, r)
		return
	}
	// A new check replaces whatever was tried before, also when it fails:
	// the page then shows the new answers, and finish must not quietly use
	// the old ones.
	s.signin = nil
	in := signinView{
		PublicURL: strings.TrimSpace(r.PostFormValue("public_url")),
		Issuer:    strings.TrimSpace(r.PostFormValue("issuer")),
		ClientID:  strings.TrimSpace(r.PostFormValue("client_id")),
	}
	secret := strings.TrimSpace(r.PostFormValue("client_secret"))
	page := func(status int, errKey, detail string) {
		p := s.page(errKey)
		p.Detail = detail
		p.Signin = s.fixSignin(in)
		s.render(w, status, p)
	}
	if s.opt.NewSignin == nil {
		page(http.StatusNotImplemented, "setup.signin.unavailable", "")
		return
	}
	if s.opt.Deployment["PUBLIC_URL"] {
		in.PublicURL = s.opt.Settings.PublicURL
	}
	pub, ok := cleanAddress(in.PublicURL, false)
	if !ok {
		key := "setup.signin.address_invalid"
		if strings.HasPrefix(in.PublicURL, "http://") {
			key = "setup.signin.address_https"
		}
		page(http.StatusUnprocessableEntity, key, "")
		return
	}
	in.PublicURL = pub
	if in.Issuer == "" || in.ClientID == "" || secret == "" {
		page(http.StatusUnprocessableEntity, "setup.signin.missing", "")
		return
	}
	if _, ok := cleanAddress(in.Issuer, true); !ok {
		page(http.StatusUnprocessableEntity, "setup.signin.issuer_invalid", "")
		return
	}
	key, err := base64.StdEncoding.DecodeString(s.opt.Keys.SessionKey)
	if err != nil {
		s.opt.Log.Error("setup: session key", "err", err)
		page(http.StatusInternalServerError, "setup.write_failed", "")
		return
	}
	flow, err := s.opt.NewSignin(r.Context(), SigninConfig{
		Issuer: in.Issuer, ClientID: in.ClientID, ClientSecret: secret,
		RedirectURL: pub + "/callback", GroupsClaim: s.opt.Settings.OIDCGroupsClaim,
		SessionKey: key, Secure: s.opt.SecureCookies || strings.HasPrefix(pub, "https://"),
	})
	if err != nil {
		page(http.StatusUnprocessableEntity, "setup.signin.discovery_failed", err.Error())
		return
	}
	in.Checked = true
	s.signin = &signinTry{view: in, secret: secret, flow: flow}
	page(http.StatusOK, "", "")
}

// handleSigninStart sends the browser to the provider. A link and not the
// form's own redirect: the console's form-action policy rightly stops a
// form from landing on another site.
func (s *Setup) handleSigninStart(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	try := s.signin
	s.mu.Unlock()
	if try == nil {
		http.Redirect(w, r, "/setup", http.StatusSeeOther)
		return
	}
	try.flow.Login(w, r)
}

// handleCallback records who signed in and sends the browser on to the
// setup page. Through a page and not a redirect, so the browser counts the
// next request as this site's own and sends the setup cookie with it. It
// shows nothing of setup itself: this request carries no setup cookie.
func (s *Setup) handleCallback(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.signin == nil {
		s.render(w, http.StatusBadRequest, setupPage{Step: "callback", Error: "setup.signin.test_failed",
			Detail: "no test sign-in was started"})
		return
	}
	u, err := s.signin.flow.Identify(w, r)
	if err != nil {
		s.render(w, http.StatusBadRequest, setupPage{Step: "callback", Error: "setup.signin.test_failed", Detail: err.Error()})
		return
	}
	s.signin.view.User = &u
	s.render(w, http.StatusOK, setupPage{Step: "callback"})
}

// finish writes the sign-in answers and restarts the console with them.
// The person who completed the test becomes owner by subject, so nobody
// has to map a group before the first sign-in. If the next start would
// refuse what was written, the old files go back and the page says why:
// a console that cannot start is worse than one still in setup.
func (s *Setup) finish(w http.ResponseWriter, r *http.Request) {
	try := s.signin
	if try == nil || try.view.User == nil {
		http.Redirect(w, r, "/setup", http.StatusSeeOther)
		return
	}
	page := func(status int, errKey, detail string) {
		p := s.page(errKey)
		p.Detail, p.Signin = detail, s.fixSignin(try.view)
		s.render(w, status, p)
	}
	oldSettings, oldKeys, err := config.ReadDataDir(s.opt.DataDir)
	if err != nil {
		s.opt.Log.Error("setup: reading the data directory", "err", err)
		page(http.StatusInternalServerError, "setup.write_failed", "")
		return
	}
	settings, keys := oldSettings, oldKeys
	settings.OwnerSubjects = append([]string(nil), oldSettings.OwnerSubjects...)
	for _, f := range []struct {
		env      string
		dst, val *string
	}{
		{"PUBLIC_URL", &settings.PublicURL, &try.view.PublicURL},
		{"OIDC_ISSUER", &settings.OIDCIssuer, &try.view.Issuer},
		{"OIDC_CLIENT_ID", &settings.OIDCClientID, &try.view.ClientID},
		{"OIDC_CLIENT_SECRET", &keys.OIDCClientSecret, &try.secret},
	} {
		if !s.opt.Deployment[f.env] {
			*f.dst = *f.val
		}
	}
	if sub := try.view.User.Subject; !slices.Contains(settings.OwnerSubjects, sub) {
		settings.OwnerSubjects = append(settings.OwnerSubjects, sub)
	}
	restore := func() {
		if err := errors.Join(config.WriteSettings(s.opt.DataDir, oldSettings),
			config.WriteKeys(s.opt.DataDir, oldKeys)); err != nil {
			s.opt.Log.Error("setup: putting the old answers back", "err", err)
		}
	}
	if err := errors.Join(config.WriteSettings(s.opt.DataDir, settings), config.WriteKeys(s.opt.DataDir, keys)); err != nil {
		s.opt.Log.Error("setup: writing the sign-in answers", "err", err)
		restore()
		page(http.StatusInternalServerError, "setup.write_failed", "")
		return
	}
	if s.opt.Check != nil {
		if err := s.opt.Check(); err != nil {
			restore()
			page(http.StatusUnprocessableEntity, "setup.signin.would_not_start", err.Error())
			return
		}
	}
	s.opt.Log.Info("setup: done, restarting", "owner", try.view.User.Subject, "issuer", try.view.Issuer)
	// The token has done its work; the cookie that carries it goes too.
	http.SetCookie(w, &http.Cookie{Name: setupCookie, Value: "", Path: "/", HttpOnly: true,
		Secure: s.opt.SecureCookies, SameSite: http.SameSiteStrictMode, MaxAge: -1})
	s.render(w, http.StatusOK, setupPage{Step: "done"})
	if s.opt.Restart != nil {
		s.opt.Restart()
	}
}

// cleanAddress accepts an http(s) URL with a host and no path, query or
// credentials, and returns it without a trailing slash. Plain http only on
// this machine: anywhere else a sign-in over it would send cookies in the
// clear, and the console refuses to start that way. A path is allowed for
// an issuer, which often has one.
func cleanAddress(v string, pathOK bool) (string, bool) {
	u, err := url.Parse(v)
	if err != nil || u.Host == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" {
		return "", false
	}
	if !pathOK && strings.Trim(u.Path, "/") != "" {
		return "", false
	}
	switch u.Scheme {
	case "https":
	case "http":
		if !config.IsLoopbackURL(v) {
			return "", false
		}
	default:
		return "", false
	}
	return strings.TrimRight(u.String(), "/"), true
}

// signinView is what the sign-in step shows. Never the secret.
type signinView struct {
	PublicURL, Issuer, ClientID string
	PublicURLFixed              bool
	RedirectURL                 string
	// Checked: the provider answered and a test sign-in can start.
	Checked bool
	// User is who signed in during the test.
	User *identity.User
}

// signinPage is the current step, with the sign-in step filled in: the
// provider being tried, or an address guessed from how the browser came.
func (s *Setup) signinPage(r *http.Request, errKey, detail string) setupPage {
	p := s.page(errKey)
	p.Detail = detail
	if p.Step != "signin" {
		return p
	}
	if s.signin != nil {
		p.Signin = s.fixSignin(s.signin.view)
		return p
	}
	v := signinView{PublicURL: s.opt.Settings.PublicURL}
	if v.PublicURL == "" {
		scheme := "http"
		if r.TLS != nil || r.Header.Get("X-Forwarded-Proto") == "https" {
			scheme = "https"
		}
		v.PublicURL = scheme + "://" + r.Host
	}
	p.Signin = s.fixSignin(v)
	return p
}

// fixSignin fills in what follows from the address and the deployment.
func (s *Setup) fixSignin(v signinView) signinView {
	if s.opt.Deployment["PUBLIC_URL"] {
		v.PublicURL, v.PublicURLFixed = strings.TrimRight(s.opt.Settings.PublicURL, "/"), true
	}
	if v.PublicURL != "" {
		v.RedirectURL = strings.TrimRight(v.PublicURL, "/") + "/callback"
	}
	return v
}

// repoForm refills the existing-repository form. Never the token.
type repoForm struct {
	URL, User string
	Tested    bool
}

// saveSettings applies change to settings.json as it is on disk, so an
// answer from an earlier step is never lost to a later one.
func (s *Setup) saveSettings(change func(*config.Settings)) error {
	cur, _, err := config.ReadDataDir(s.opt.DataDir)
	if err != nil {
		return err
	}
	change(&cur)
	return config.WriteSettings(s.opt.DataDir, cur)
}

type setupStep struct {
	Name, Key     string
	Current, Done bool
}

type setupPage struct {
	L     Localizer
	Step  string
	Steps []setupStep
	Error string
	// Detail is what the failing tool said, under the explanation in Error.
	Detail          string
	RecoveryOffered bool
	Repo            repoForm
	Signin          signinView
}

// step is the first one not yet done. Each is done when its answer is in
// force, from the deployment or from the data directory, so a deployment
// that already set something skips its step without being asked.
func (s *Setup) step() string {
	k := s.opt.Keys
	switch {
	case k.SessionKey == "" || k.SecretKey == "" || k.CheckinToken == "":
		return "keys"
	case s.opt.Settings.RepoDir == "":
		return "repo"
	default:
		return "signin"
	}
}

func (s *Setup) page(errKey string) setupPage {
	cur := s.step()
	p := setupPage{Step: cur, Error: errKey}
	done := true
	for _, st := range []setupStep{{Name: "keys", Key: "setup.step.keys"},
		{Name: "repo", Key: "setup.step.repo"}, {Name: "signin", Key: "setup.step.signin"}} {
		if st.Name == cur {
			done = false
		}
		st.Current, st.Done = st.Name == cur, done
		p.Steps = append(p.Steps, st)
	}
	p.RecoveryOffered = s.pending.SecretKey != "" || (!s.opt.Deployment["SECRET_KEY"] && s.opt.Keys.SecretKey != "")
	return p
}

// renderLocked renders the current step with an error; the caller holds mu.
func (s *Setup) renderLocked(w http.ResponseWriter, status int, errKey string) {
	s.render(w, status, s.page(errKey))
}

func (s *Setup) render(w http.ResponseWriter, status int, p setupPage) {
	p.L = newLocalizer(identity.Preferences{}, s.opt.Locale, "UTC")
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	w.Header().Set("Cache-Control", "no-store")
	w.WriteHeader(status)
	if err := s.tmpl.ExecuteTemplate(w, "setup", p); err != nil {
		s.opt.Log.Error("setup: render", "err", err)
	}
}
